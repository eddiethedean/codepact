"""Generate or check Rust identifier tables using each target's CPython runtime.

Run with uv run --no-project --python 3.11 python scripts/generate_identifier_tables.py
and repeat for 3.12 and 3.13. Pass --check to verify the checked-in tables.
"""

from pathlib import Path
import sys
import unicodedata


def ranges(points: list[int]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for point in points:
        if result and point == result[-1][1] + 1:
            result[-1] = (result[-1][0], point)
        else:
            result.append((point, point))
    return result


def table(name: str, points: list[int]) -> str:
    entries = "".join(
        f"    (0x{start:X}, 0x{end:X}),\n" for start, end in ranges(points)
    )
    return f"pub(super) const {name}: &[(u32, u32)] = &[\n{entries}];\n"


def main() -> None:
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: generate_identifier_tables.py [--check]")
    check = sys.argv[1:] == ["--check"]
    version = (sys.version_info.major, sys.version_info.minor)
    unicode_versions = {(3, 11): "14.0.0", (3, 12): "15.0.0", (3, 13): "15.1.0"}
    expected = unicode_versions.get(version)
    if expected is None:
        if check:
            print(f"No analyzer identifier table claimed for Python {version}")
            return
        raise SystemExit("Generate tables using CPython 3.11, 3.12 or 3.13")
    if sys.implementation.name != "cpython" or unicodedata.unidata_version != expected:
        raise SystemExit("The interpreter does not match the qualified Unicode version")
    starts = [point for point in range(0x110000) if chr(point).isidentifier()]
    start_set = set(starts)
    continuation = [
        point
        for point in range(0x110000)
        if point not in start_set and ("A" + chr(point)).isidentifier()
    ]
    content = (
        "// Generated by scripts/generate_identifier_tables.py; do not edit.\n"
        f"// CPython {version[0]}.{version[1]}, Unicode {expected}.\n\n"
        + table("START", starts)
        + "\n"
        + table("CONTINUE_ONLY", continuation)
    )
    root = Path(__file__).resolve().parent.parent
    path = (
        root
        / "crates/codepact/src/identifiers"
        / (f"python{version[0]}{version[1]}.rs")
    )
    if check:
        if path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Identifier table differs from CPython: {path}")
        print(f"Identifier table matches CPython {version[0]}.{version[1]}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
